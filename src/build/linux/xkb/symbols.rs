//! The text of `xkb/symbols/<L>` (`linux.xkb.symbols`).

use std::fmt::Write as _;

use super::keycodes::{DECIMAL, XkbKey};
use super::keysym::Keysym;
use super::types::KeyType;

/// A key as the symbols file writes it.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct SymbolsKey {
    pub key: XkbKey,
    pub key_type: KeyType,
    pub levels: Vec<Keysym>,
}

/// Everything the symbols file of one layout holds.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Symbols {
    pub id: String,
    /// The layout's file name in `layouts/`.
    pub file: String,
    pub description: String,
    pub keys: Vec<SymbolsKey>,
    /// The keysym Num Lock selects at `<KPDL>`, for a keyboard with a
    /// `decimal`.
    pub decimal: Option<Keysym>,
    pub uses_level3: bool,
}

/// `text` as an XKB string literal's contents: `\` and `"` escaped by `\`.
fn escape(text: &str) -> String {
    let mut out = String::with_capacity(text.len());
    for c in text.chars() {
        if c == '\\' || c == '"' {
            out.push('\\');
        }
        out.push(c);
    }
    out
}

fn key_line(out: &mut String, key: XkbKey, key_type: KeyType, levels: &[Keysym]) {
    let names: Vec<String> = levels.iter().map(|keysym| keysym.name()).collect();
    let _ = writeln!(
        out,
        "    key <{}> {{ type[Group1] = \"{}\", symbols[Group1] = [ {} ] }};",
        key.name,
        key_type.name(),
        names.join(", ")
    );
}

/// The file's text. The one section is the default, so the layout name
/// alone selects it: xkeyboard-config's evdev rules map a layout L to
/// `symbols/L` and add `pc` and `inet(evdev)`, which keep every key the
/// file does not define.
// [spec:kbdgen:syn:linux.xkb.symbols]
// [spec:kbdgen:sem:linux.xkb.naming]
pub fn write(symbols: &Symbols) -> String {
    let mut out = String::new();
    let _ = writeln!(
        out,
        "// {}: generated by kbdgen from layouts/{}. Do not edit.",
        symbols.id, symbols.file
    );
    out.push_str("default partial alphanumeric_keys\n");
    out.push_str("xkb_symbols \"basic\" {\n");
    let _ = writeln!(
        out,
        "    name[Group1] = \"{}\";",
        escape(&symbols.description)
    );
    for key in &symbols.keys {
        key_line(&mut out, key.key, key.key_type, &key.levels);
    }
    if let Some(decimal) = symbols.decimal {
        key_line(
            &mut out,
            DECIMAL,
            KeyType::Keypad,
            &[Keysym::KP_DELETE, decimal],
        );
    }
    if symbols.uses_level3 {
        out.push_str("    include \"level3(ralt_switch)\"\n");
    }
    out.push_str("};\n");
    out
}
