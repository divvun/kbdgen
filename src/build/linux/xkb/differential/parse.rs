//! Reads a written symbols file back, as `linux.xkb.symbols` lays it out.

use anyhow::{Context, Result, anyhow, bail};

use crate::build::linux::xkb::keysym::Keysym;
use crate::build::linux::xkb::types::KeyType;

/// One `key` line.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct ParsedKey {
    pub name: String,
    pub key_type: KeyType,
    pub levels: Vec<Keysym>,
}

/// A symbols file read back.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Parsed {
    pub description: String,
    pub keys: Vec<ParsedKey>,
    pub level3: bool,
}

impl Parsed {
    pub fn key(&self, name: &str) -> Option<&ParsedKey> {
        self.keys.iter().find(|key| key.name == name)
    }
}

fn key_line(line: &str) -> Result<ParsedKey> {
    let rest = line
        .strip_prefix("    key <")
        .ok_or_else(|| anyhow!("not a key line: {line:?}"))?;
    let (name, rest) = rest
        .split_once("> { type[Group1] = \"")
        .ok_or_else(|| anyhow!("no type: {line:?}"))?;
    let (type_name, rest) = rest
        .split_once("\", symbols[Group1] = [ ")
        .ok_or_else(|| anyhow!("no symbols: {line:?}"))?;
    let keysyms = rest
        .strip_suffix(" ] };")
        .ok_or_else(|| anyhow!("unterminated: {line:?}"))?;
    let key_type =
        KeyType::from_name(type_name).ok_or_else(|| anyhow!("unknown type {type_name:?}"))?;
    let levels = keysyms
        .split(", ")
        .map(|name| Keysym::from_name(name).ok_or_else(|| anyhow!("unknown keysym {name:?}")))
        .collect::<Result<Vec<_>>>()?;
    if levels.len() != key_type.levels() {
        bail!("{line:?}: {} levels for {type_name}", levels.len());
    }
    Ok(ParsedKey {
        name: name.to_owned(),
        key_type,
        levels,
    })
}

/// Parses a symbols file of layout `id`, refusing anything
/// `linux.xkb.symbols` does not lay out.
pub fn parse(text: &str, id: &str) -> Result<Parsed> {
    let body = text
        .strip_suffix("};\n")
        .ok_or_else(|| anyhow!("{id}: the file does not end with \"}};\" and a newline"))?;
    let mut lines = body.lines();
    let comment = lines.next().unwrap_or_default();
    if !(comment.starts_with(&format!("// {id}: generated by kbdgen from layouts/"))
        && comment.ends_with(". Do not edit."))
    {
        bail!("{id}: bad comment line {comment:?}");
    }
    if lines.next() != Some("default partial alphanumeric_keys")
        || lines.next() != Some("xkb_symbols \"basic\" {")
    {
        bail!("{id}: the section is not the default \"basic\"");
    }
    let name = lines.next().unwrap_or_default();
    let description = name
        .strip_prefix("    name[Group1] = \"")
        .and_then(|rest| rest.strip_suffix("\";"))
        .ok_or_else(|| anyhow!("{id}: bad name line {name:?}"))?
        .replace("\\\"", "\"")
        .replace("\\\\", "\\");
    let mut keys = Vec::new();
    let mut level3 = false;
    for line in lines {
        if level3 {
            bail!("{id}: {line:?} after the include");
        }
        if line == "    include \"level3(ralt_switch)\"" {
            level3 = true;
            continue;
        }
        keys.push(key_line(line).with_context(|| id.to_owned())?);
    }
    Ok(Parsed {
        description,
        keys,
        level3,
    })
}
