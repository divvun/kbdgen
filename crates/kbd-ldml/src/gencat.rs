fn in_table(table: &[(char, char)], c: char) -> bool {
    table
        .binary_search_by(|&(lo, hi)| {
            if hi < c {
                Ordering::Less
            } else if lo > c {
                Ordering::Greater
            } else {
                Ordering::Equal
            }
        })
        .is_ok()
}

/// Whether `c` is of general category M.
pub fn is_mark(c: char) -> bool {
    in_table(MARKS, c)
}

/// Whether `c` is of general category M, Cc, Cf or Z; U+0020 included.
pub(crate) fn needs_escape(c: char) -> bool {
    in_table(MARKS, c) || in_table(CONTROL_FORMAT_SEPARATOR, c)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn tables_are_sorted_and_disjoint() {
        for table in [MARKS, CONTROL_FORMAT_SEPARATOR] {
            for pair in table.windows(2) {
                assert!(pair[0].0 <= pair[0].1);
                assert!(pair[0].1 < pair[1].0, "{pair:?}");
            }
        }
    }

    #[test]
    fn classifies_marks_controls_formats_separators() {
        for c in [
            '\u{301}', '\u{9CD}', '\u{9BE}', '\u{0}', '\u{7F}', '\u{200C}', '\u{A0}', ' ',
        ] {
            assert!(needs_escape(c), "{c:?}");
        }
        for c in ['a', '´', 'ŋ', '\u{25CC}', '\u{E000}'] {
            assert!(!needs_escape(c), "{c:?}");
        }
        assert!(is_mark('\u{301}'));
        assert!(is_mark('\u{9BE}'));
        assert!(!is_mark('\u{200C}'));
        assert!(!is_mark('\u{A0}'));
        assert!(!is_mark('a'));
    }
}
